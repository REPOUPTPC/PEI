function normalizeString(str) {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, '');
}

const cleanedList = [];
const seenKeys = new Map();

for (const row of parsed.data) {
  let name = row.Nombre_Unidad_Curricular;
  if (!name || name.trim().toUpperCase() === 'NULL') continue;

  name = name.trim().replace(/\\+$/, '').trim().replace(/^["']|["']$/g, '').trim().replace(/\s+/g, ' ');

  if (manualCorrections[name]) {
    name = manualCorrections[name];
  }

  // Also check if after manual correction it still matches another normalized string
  const norm = normalizeString(name);
  if (!seenKeys.has(norm)) {
    seenKeys.set(norm, name);
    cleanedList.push({
      nombre: name,
      norm: norm,
      ejemploCodigo: row.Codigo,
      ejemploPensum: row.Pensum,
    });
  }
}

// Sort alphabetically
cleanedList.sort((a, b) => a.nombre.localeCompare(b.nombre, 'es'));

